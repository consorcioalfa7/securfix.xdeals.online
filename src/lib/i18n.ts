export type Locale = 'pt' | 'es' | 'fr' | 'en' | 'de' | 'nl' | 'it';

export interface LocaleInfo {
  code: Locale;
  label: string;
  flag: string;
  nativeLabel: string;
}

export const AVAILABLE_LOCALES: LocaleInfo[] = [
  { code: 'pt', label: 'Português', flag: '🇵🇹', nativeLabel: 'Português' },
  { code: 'es', label: 'Español', flag: '🇪🇸', nativeLabel: 'Español' },
  { code: 'fr', label: 'Français', flag: '🇫🇷', nativeLabel: 'Français' },
  { code: 'en', label: 'English', flag: '🇬🇧', nativeLabel: 'English' },
  { code: 'de', label: 'Deutsch', flag: '🇩🇪', nativeLabel: 'Deutsch' },
  { code: 'nl', label: 'Nederlands', flag: '🇳🇱', nativeLabel: 'Nederlands' },
  { code: 'it', label: 'Italiano', flag: '🇮🇹', nativeLabel: 'Italiano' },
];

const DEFAULT_LOCALE: Locale = 'pt';

function detectBrowserLocale(): Locale {
  if (typeof navigator === 'undefined') return DEFAULT_LOCALE;
  const lang = navigator.language.split('-')[0].toLowerCase();
  const found = AVAILABLE_LOCALES.find(l => l.code === lang);
  return found ? found.code : DEFAULT_LOCALE;
}

function getStoredLocale(): Locale | null {
  if (typeof localStorage === 'undefined') return null;
  const stored = localStorage.getItem('securfix-locale');
  if (stored && AVAILABLE_LOCALES.some(l => l.code === stored)) {
    return stored as Locale;
  }
  return null;
}

export function getInitialLocale(): Locale {
  return getStoredLocale() ?? detectBrowserLocale();
}

